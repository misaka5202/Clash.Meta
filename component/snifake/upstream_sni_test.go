// originTLS is a TLS server that records the SNI the client presented.
func originTLS(t *testing.T, gotSNI chan<- string) func(net.Conn) {
	return func(c net.Conn) {
		defer c.Close()
		key, _ := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		tmpl := &x509.Certificate{
			SerialNumber:          big.NewInt(1),
			Subject:               pkix.Name{CommonName: "origin.test"},
			NotBefore:             time.Now().Add(-time.Hour),
			NotAfter:              time.Now().Add(time.Hour),
			KeyUsage:              x509.KeyUsageDigitalSignature,
			ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
			BasicConstraintsValid: true,
			DNSNames:              []string{"origin.test", "benign.example"},
		}
		der, _ := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
		tc := tls.Server(c, &tls.Config{Certificates: []tls.Certificate{{
			Certificate: [][]byte{der}, PrivateKey: key,
		}}})
		if err := tc.Handshake(); err != nil {
			return
		}
		select {
		case gotSNI <- tc.ConnectionState().ServerName:
		default:
		}
		_, _ = io.WriteString(tc, "ok\n")
	}
}

// TestUpstreamSNIIsAlias proves the wire SNI the ORIGIN sees is the alias,
// not the real domain. The client hello the origin receives is generated by
// the MITM bridge, so this is the only place the rewrite can be observed.
func TestUpstreamSNIIsAlias(t *testing.T) {
	ResetRules()
	defer ResetRules()
	if err := AddCealingRule([]any{[]any{"origin.test"}, "benign.example", "127.0.0.1"}); err != nil {
		t.Fatal(err)
	}

	gotSNI := make(chan string, 1)
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer ln.Close()
	handler := originTLS(t, gotSNI)
	go func() {
		for {
			c, err := ln.Accept()
			if err != nil {
				return
			}
			go handler(c)
		}
	}()

	real, err := net.Dial("tcp", ln.Addr().String())
	if err != nil {
		t.Fatal(err)
	}
	m := ApplyDirect(real, "origin.test")

	s, err := EnsureSigner()
	if err != nil {
		t.Fatal(err)
	}
	pool := x509.NewCertPool()
	if !pool.AppendCertsFromPEM([]byte(s.RootPEM())) {
		t.Fatal("cannot add root to pool")
	}
	app := tls.Client(m, &tls.Config{ServerName: "origin.test", RootCAs: pool})
	if err := app.Handshake(); err != nil {
		t.Fatal("app handshake:", err)
	}
	line, _ := bufio.NewReader(app).ReadString('\n')
	if line != "ok\n" {
		t.Fatalf("payload mismatch: %q", line)
	}
	select {
	case sni := <-gotSNI:
		if sni != "benign.example" {
			t.Fatalf("upstream SNI = %q, want %q", sni, "benign.example")
		}
	case <-time.After(5 * time.Second):
		t.Fatal("origin never reported an SNI")
	}
}
